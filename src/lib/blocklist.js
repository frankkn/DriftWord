// 簡單的黑名單字詞過濾（客戶端）。
//
// 取捨說明：
// - 這是客戶端檢查，可被技術手段繞過。屬於「簡單擋一線」的方案。
// - DriftWord 鼓勵憂傷、孤獨、對死亡的省思等脆弱表達——那是產品核心。
//   所以清單刻意偏向「對他人的攻擊/辱罵/威脅」與明確仇恨字眼，
//   盡量避開可能出現在「自我傾訴」裡的字（例如單獨的「想死」「廢物」）。
// - 要增刪就改下面這個陣列即可。

const BLOCKED = [
  // 針對他人的辱罵 / 攻擊
  '幹你', '幹你娘', '操你', '操你媽', '你媽死', '你全家',
  '你去死', '去死吧', '死全家', '你這種垃圾', '你這種人渣',
  // 威脅他人
  '殺了你', '宰了你', '弄死你', '打死你', '砍死你',
  // 仇恨 / 歧視（示意，可再補）
  '支那', '死黑鬼',
  // 露骨騷擾（示意，可再補）
  '幹爆', '強姦你',
]

// 找出文字裡命中的第一個黑名單字詞，沒有則回傳 null。
export function findBlockedWord(text) {
  const t = text || ''
  return BLOCKED.find((w) => t.includes(w)) || null
}
